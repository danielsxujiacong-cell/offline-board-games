import json
import pathlib
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "wavelength" / "questions.json"
JS_OUT = ROOT / "wavelength" / "questions-data.js"
EDGE_OUT = ROOT / "supabase" / "functions" / "_shared" / "wavelength" / "questions.json"

EXPECTED_PACKS = {
    "边界与直觉": 35,
    "吃喝与消费": 35,
    "生活与脑洞": 35,
    "观点与社交": 35,
    "情侣日常": 40,
    "微醺暧昧": 30,
}

def main():
    raw = SRC.read_text(encoding="utf-8")
    questions = json.loads(raw)
    assert isinstance(questions, list), "questions.json must be an array"
    assert len(questions) == sum(EXPECTED_PACKS.values()), f"Expected {sum(EXPECTED_PACKS.values())} questions, got {len(questions)}"

    counts = {}
    seen = set()
    for idx, row in enumerate(questions, 1):
        assert isinstance(row, list) and len(row) == 4, f"Row {idx} must be [category, left, right, hints]"
        cat, left, right, hints = row
        for field_name, val in [("category", cat), ("left", left), ("right", right), ("hints", hints)]:
            assert isinstance(val, str) and val.strip() == val and len(val) > 0, f"Row {idx} {field_name} invalid: {val!r}"
            assert "\n" not in val and "\r" not in val and "<" not in val and ">" not in val, f"Row {idx} illegal chars: {val!r}"
        assert 1 <= len(left) <= 6, f"Row {idx} left too long ({len(left)}): {left!r}"
        assert 1 <= len(right) <= 6, f"Row {idx} right too long ({len(right)}): {right!r}"
        assert left != right, f"Row {idx} identical endpoints: {left!r}"
        assert 2 <= len(hints) <= 40, f"Row {idx} hints invalid length: {hints!r}"

        pair_key = "|".join(sorted(
            unicodedata.normalize("NFKC", s).replace(" ", "")
            for s in (left, right)
        ))
        assert pair_key not in seen, f"Row {idx} duplicate or reversed pair: {left} / {right}"
        seen.add(pair_key)
        counts[cat] = counts.get(cat, 0) + 1

    assert list(counts.keys()) == list(EXPECTED_PACKS.keys()), f"Pack order mismatch: {list(counts.keys())}"
    for cat, expected in EXPECTED_PACKS.items():
        assert counts[cat] == expected, f"Pack {cat} expected {expected}, got {counts[cat]}"

    compact_json = json.dumps(questions, ensure_ascii=False, separators=(",", ":"))
    JS_OUT.write_text(
        "// Auto-generated by scripts/wavelength-sync.py from questions.json\n"
        f"export const QUESTIONS = {compact_json};\n",
        encoding="utf-8",
    )
    EDGE_OUT.write_text(raw, encoding="utf-8")
    assert EDGE_OUT.read_text(encoding="utf-8") == raw

    print(f"PASS: {len(questions)} questions across {len(counts)} packs synced to questions-data.js and supabase edge shared questions.json")
    for k, v in counts.items():
        print(f"  - {k}: {v}")

if __name__ == "__main__":
    main()
